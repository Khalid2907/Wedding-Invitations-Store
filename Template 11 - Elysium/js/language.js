class LanguageManager {
  constructor() {
    this.currentLang = 'en';
  }

  init() {
    const savedLang = localStorage.getItem('elysium_lang') || 'en';
    this.setLanguage(savedLang);
    this.bindEvents();
  }

  bindEvents() {
    const langBtn = document.getElementById('lang-toggle-btn');
    if (langBtn) {
      langBtn.addEventListener('click', () => {
        const nextLang = this.currentLang === 'en' ? 'ar' : 'en';
        this.setLanguage(nextLang);
      });
    }
  }

  setLanguage(lang) {
    if (!DICTIONARY[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('elysium_lang', lang);

    const html = document.documentElement;
    html.setAttribute('lang', lang);
    html.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

    const dict = DICTIONARY[lang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = dict[key];
        } else {
          el.textContent = dict[key];
        }
      }
    });

    const langTextEl = document.getElementById('lang-text');
    if (langTextEl) {
      langTextEl.textContent = lang === 'en' ? 'العربية' : 'English';
    }

    document.title = dict.metaTitle;
  }

  t(key) {
    return DICTIONARY[this.currentLang][key] || key;
  }
}

window.languageManager = new LanguageManager();
